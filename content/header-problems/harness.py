class HarnessError(Exception):
    """A content or configuration error, reported with the problem's name."""


def require_container() -> None:
    """Refuse to run on the host: timings and the PDF must come from the image."""
    if not CONTAINER_MARKER.exists():
        raise HarnessError(
            "this script must run inside the oj-content-build image.\n"
            "Use the driver instead, from content/header-problems/:\n"
            "    ./run.sh build  --all\n"
            "    ./run.sh verify --all"
        )


# --- meta.json -------------------------------------------------------------


@dataclass(frozen=True)
class Subtask:
    cases: int
    percent: int
    note: str


@dataclass(frozen=True)
class Meta:
    id: str
    title: str
    author: str
    topic: str
    cls: str
    categories: list[str]
    difficulty: int | None
    collection: str | None
    time_limit_ms: int
    memory_limit_mb: int
    submission_filename: str
    declarations: list[str]
    has_tle_subtask: bool
    subtasks: list[Subtask]
    pdf_probe: str
    source_dir: Path

    @property
    def ds_filename(self) -> str:
        return TOPICS[self.topic]

    @property
    def dist_dir(self) -> Path:
        return DIST_DIR / self.id

    @property
    def work_dir(self) -> Path:
        return WORK_DIR / self.id

    @property
    def time_limit_s(self) -> float:
        return self.time_limit_ms / 1000.0


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise HarnessError(message)


def load_meta(problem_dir: Path) -> Meta:
    """Read and fully validate one problem's meta.json.

    Every rule the OJ's own importer enforces is checked here, so a problem
    that builds is a problem that imports: id shape and length, title/author
    length, the closed category set, the 800-3500 step-100 difficulty scale,
    the minimum time/memory limits, and the submission filename rule. On top
    of that, the harness checks the subtask table really does reproduce the
    judge's prefix score.
    """
    path = problem_dir / "meta.json"
    _require(path.is_file(), f"{problem_dir.name}: meta.json is missing")
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise HarnessError(f"{problem_dir.name}: meta.json is not valid JSON: {error}") from error

    def field(name: str, kind: type, *, optional: bool = False, default=None):
        if name not in raw:
            _require(optional, f"{problem_dir.name}: meta.json is missing \"{name}\"")
            return default
        value = raw[name]
        if optional and value is None:
            return default
        # `bool` is a subclass of `int` in Python, so an explicit int field
        # must reject `true` and vice versa.
        ok = isinstance(value, kind) and (kind is bool) == isinstance(value, bool)
        _require(ok, f"{problem_dir.name}: meta.json \"{name}\" must be {kind.__name__}")
        return value

    problem_id = field("id", str)
    _require(problem_id == problem_dir.name,
             f"{problem_dir.name}: meta.json id \"{problem_id}\" must equal the directory name")
    _require(len(problem_id) <= MAX_PROBLEM_ID_LENGTH,
             f"{problem_id}: id is longer than {MAX_PROBLEM_ID_LENGTH} characters")
    _require(bool(PROBLEM_ID_PATTERN.match(problem_id)),
             f"{problem_id}: id must look like hp_<topic><nn>_<name> (lowercase, digits, underscores)")

    title = field("title", str).strip()
    _require(1 <= len(title) <= MAX_TITLE_LENGTH, f"{problem_id}: title must be 1..{MAX_TITLE_LENGTH} characters")
    author = field("author", str).strip()
    _require(len(author) >= 1, f"{problem_id}: author must not be empty")

    topic = field("topic", str)
    _require(topic in TOPICS, f"{problem_id}: unknown topic \"{topic}\" (expected one of {', '.join(sorted(TOPICS))})")
    cls = field("class", str)

    categories = field("categories", list, optional=True, default=[]) or []
    for category in categories:
        _require(category in PROBLEM_CATEGORIES, f"{problem_id}: unknown category \"{category}\"")

    difficulty = raw.get("difficulty")
    if difficulty is not None:
        _require(isinstance(difficulty, int) and not isinstance(difficulty, bool),
                 f"{problem_id}: difficulty must be an integer or null")
        _require(DIFFICULTY_MIN <= difficulty <= DIFFICULTY_MAX and difficulty % DIFFICULTY_STEP == 0,
                 f"{problem_id}: difficulty must be {DIFFICULTY_MIN}..{DIFFICULTY_MAX} in steps of {DIFFICULTY_STEP}")

    collection = raw.get("collection")
    if collection is not None:
        _require(isinstance(collection, str) and collection.strip() != "",
                 f"{problem_id}: collection must be a non-empty string or null")
        collection = collection.strip()

    time_limit_ms = field("time_limit_ms", int)
    _require(time_limit_ms >= MIN_TIME_LIMIT_MS, f"{problem_id}: time_limit_ms must be >= {MIN_TIME_LIMIT_MS}")
    memory_limit_mb = field("memory_limit_mb", int)
    _require(memory_limit_mb >= MIN_MEMORY_LIMIT_MB, f"{problem_id}: memory_limit_mb must be >= {MIN_MEMORY_LIMIT_MB}")

    submission_filename = field("submission_filename", str, optional=True, default="student.h")
    _require(bool(FILENAME_PATTERN.match(submission_filename)),
             f"{problem_id}: submission_filename \"{submission_filename}\" is not a valid flat filename")
    _require(Path(submission_filename).suffix.lower() in {".h", ".hpp"},
             f"{problem_id}: submission_filename must end in .h or .hpp")

    declarations = field("declarations", list)
    _require(len(declarations) > 0 and all(isinstance(line, str) for line in declarations),
             f"{problem_id}: declarations must be a non-empty list of strings")

    _require(isinstance(raw.get("has_tle_subtask"), bool),
             f"{problem_id}: has_tle_subtask must be true or false")
    has_tle_subtask = raw["has_tle_subtask"]

    subtasks_raw = field("subtasks", list)
    _require(len(subtasks_raw) > 0, f"{problem_id}: subtasks must not be empty")
    subtasks: list[Subtask] = []
    for index, entry in enumerate(subtasks_raw, start=1):
        _require(isinstance(entry, dict), f"{problem_id}: subtask {index} must be an object")
        for key in ("cases", "percent", "note"):
            _require(key in entry, f"{problem_id}: subtask {index} is missing \"{key}\"")
        _require(isinstance(entry["cases"], int) and entry["cases"] > 0,
                 f"{problem_id}: subtask {index} \"cases\" must be a positive integer")
        _require(isinstance(entry["percent"], int) and entry["percent"] > 0,
                 f"{problem_id}: subtask {index} \"percent\" must be a positive integer")
        subtasks.append(Subtask(entry["cases"], entry["percent"], str(entry["note"])))

    _require(sum(s.cases for s in subtasks) == TESTCASE_COUNT,
             f"{problem_id}: subtask case counts must add up to {TESTCASE_COUNT}")
    _require(sum(s.percent for s in subtasks) == 100,
             f"{problem_id}: subtask percentages must add up to 100")

    # The judge runs cases in order, stops at the first failure and scores
    # round(passed / total * 100) (judgeService.ts). So a subtask boundary is
    # only meaningful if its cumulative percentage equals that formula at the
    # same cumulative case count; otherwise the statement promises a score the
    # judge cannot produce.
    cumulative_cases = 0
    cumulative_percent = 0
    for index, subtask in enumerate(subtasks, start=1):
        cumulative_cases += subtask.cases
        cumulative_percent += subtask.percent
        expected = round(cumulative_cases / TESTCASE_COUNT * 100)
        _require(cumulative_percent == expected,
                 f"{problem_id}: after subtask {index} the statement promises {cumulative_percent}% "
                 f"but the judge's prefix score for {cumulative_cases}/{TESTCASE_COUNT} cases is {expected}%")

    pdf_probe = field("pdf_probe", str)
    _require(len(pdf_probe.strip()) >= 8,
             f"{problem_id}: pdf_probe must be a distinctive Thai phrase from statement.md (>= 8 characters)")

    for required in ("statement.md", "starter_main.cpp", "grader_main.cpp",
                     "student_template.h", "solution.h", "slow.h", "gen.py"):
        _require((problem_dir / required).is_file(), f"{problem_id}: {required} is missing")

    return Meta(
        id=problem_id,
        title=title,
        author=author,
        topic=topic,
        cls=cls,
        categories=list(categories),
        difficulty=difficulty,
        collection=collection,
        time_limit_ms=time_limit_ms,
        memory_limit_mb=memory_limit_mb,
        submission_filename=submission_filename,
        declarations=[str(line) for line in declarations],
        has_tle_subtask=has_tle_subtask,
        subtasks=subtasks,
        pdf_probe=pdf_probe,
        source_dir=problem_dir,
    )


def all_problem_dirs() -> list[Path]:
    if not PROBLEMS_DIR.is_dir():
        return []
    return sorted(path for path in PROBLEMS_DIR.iterdir() if path.is_dir() and not path.name.startswith("."))


def resolve_problem_dirs(selectors: list[str]) -> list[Path]:
    """`--all` (or nothing) = every problem; otherwise the named ids."""
    if not selectors or selectors == ["--all"]:
        dirs = all_problem_dirs()
        if not dirs:
            raise HarnessError(f"no problems found under {PROBLEMS_DIR}")
        return dirs
    chosen = []
    for selector in selectors:
        path = PROBLEMS_DIR / selector
        if not path.is_dir():
            raise HarnessError(f"unknown problem \"{selector}\" (no directory {path})")
        chosen.append(path)
    return chosen


# --- header composition ----------------------------------------------------


def compose_header(meta: Meta) -> str:
    """lib/<topic>.h + the problem's own declarations -> the shipped <ds>.h.

    The marker line's indentation is reused for every injected line, so the
    class body stays readable whatever the author writes. `declarations`
    entries may be bare prototypes or complete inline definitions — the
    harness does not care, which is what lets one mechanism serve problems
    that move a pre-existing member into student.h and problems that leave it
    implemented in the header.
    """
    template_path = LIB_DIR / meta.ds_filename
    _require(template_path.is_file(), f"{meta.id}: missing topic template {template_path}")
    text = template_path.read_text(encoding="utf-8")

    marker_lines = [line for line in text.splitlines() if DECLARATIONS_MARKER in line]
    _require(len(marker_lines) == 1,
             f"{meta.id}: {template_path.name} must contain exactly one {DECLARATIONS_MARKER} marker")
    marker_line = marker_lines[0]
    indent = marker_line[: len(marker_line) - len(marker_line.lstrip())]

    injected: list[str] = []
    for entry in meta.declarations:
        for line in entry.splitlines() or [""]:
            injected.append(indent + line if line.strip() else "")
    return text.replace(marker_line, "\n".join(injected))


# --- statement assembly ----------------------------------------------------


def subtask_section(meta: Meta) -> str:
    """The generated `## Subtasks :` section, in the template's numbered-list
    form (`1. (20 points) <condition>`).

    Generated, not authored, so the percentages printed in the PDF can never
    drift from meta.json — and meta.json is the thing validated against the
    judge's prefix-score formula. The cumulative score is not printed per row
    (the template's list has no column for it); the sentence above the list
    states the stop-on-first-failure rule that makes the prefix sum the real
    score, which is why the subtasks are listed smallest-first.
    """
    lines = [
        "## Subtasks :",
        "",
        f"ข้อนี้มีชุดทดสอบ {TESTCASE_COUNT} ชุด เรียงจากชุดเล็กไปชุดใหญ่ ระบบตรวจจะหยุด"
        "ที่ชุดแรกที่ตอบผิดหรือใช้เวลาเกิน คะแนนที่ได้คือสัดส่วนของชุดที่ผ่านติดต่อกัน"
        "ตั้งแต่ชุดแรก",
        "",
    ]
    first = 1
    for number, subtask in enumerate(meta.subtasks, start=1):
        last = first + subtask.cases - 1
        span = f"{first}" if first == last else f"{first}–{last}"
        lines.append(f"{number}. ({subtask.percent} points) ชุดทดสอบที่ {span} : {subtask.note}")
        first = last + 1
    return "\n".join(lines)


def limits_section(meta: Meta) -> str:
    """The generated `## Limits :` section.

    The limits the judge enforces live in meta.json, so they are printed from
    it rather than typed into the statement a second time.
    """
    seconds = f"{meta.time_limit_ms / 1000:g}"
    return "\n".join([
        "## Limits :",
        "",
        f"* Time limit: {seconds} seconds",
        f"* Memory limit: {meta.memory_limit_mb} MB",
    ])


def expand_placeholders(text: str, meta: Meta) -> str:
    replacements = {
        "{{id}}": meta.id,
        "{{title}}": meta.title,
        "{{ds}}": meta.ds_filename,
        "{{submission}}": meta.submission_filename,
        "{{class}}": meta.cls,
        "{{topic}}": meta.topic,
    }
    for key, value in replacements.items():
        text = text.replace(key, value)
    return text


TITLE_HEADING_RE = re.compile(r"^#\s+(.*)$")


def _split_title(meta: Meta, text: str) -> str:
    """Check the statement's `# <Title>` line and remove it.

    The template opens with the title as an H1. The PDF's H1 is rendered by
    build.py from meta.json (which is also what config.json and the OJ's
    problem list show), so the one in statement.md is checked for equality and
    then dropped rather than rendered — that way the two can never disagree,
    and the author still sees the title at the top of the file.
    """
    lines = text.replace("\r\n", "\n").split("\n")
    first = next((index for index, line in enumerate(lines) if line.strip()), None)
    if first is None:
        raise HarnessError(f"{meta.id}: statement.md is empty")
    heading = TITLE_HEADING_RE.match(lines[first])
    if not heading:
        raise HarnessError(
            f"{meta.id}: statement.md must start with the title as \"# {meta.title}\" "
            f"(found {lines[first].strip()[:60]!r})"
        )
    found = heading.group(1).strip()
    if found != meta.title:
        raise HarnessError(
            f"{meta.id}: statement.md's title \"{found}\" does not match meta.json's \"{meta.title}\""
        )
    del lines[first]
    return "\n".join(lines)


def assemble_statement_markdown(meta: Meta) -> str:
    """statement.md + the shared partials + the generated subtasks and limits.

    Shared by build.py (which renders it) and verify.py (which re-extracts the
    sample from it), so the sample the statement SHOWS is the sample the
    starter is verified against.
    """
    text = (meta.source_dir / "statement.md").read_text(encoding="utf-8")
    text = _split_title(meta, text)

    for placeholder, filename in (("{{> rules}}", "rules.md"), ("{{> author}}", "author.md")):
        if placeholder not in text:
            raise HarnessError(
                f"{meta.id}: statement.md must include the shared partial with {placeholder}")
        partial = (STATEMENT_DIR / filename).read_text(encoding="utf-8")
        text = text.replace(placeholder, partial.strip())

    for placeholder, section in (("{{subtasks}}", subtask_section(meta)),
                                 ("{{limits}}", limits_section(meta))):
        if placeholder not in text:
            raise HarnessError(
                f"{meta.id}: statement.md must place the generated section with {placeholder}")
        text = text.replace(placeholder, section)

    text = expand_placeholders(text, meta)

    # HTML comments never reach the PDF, and the partial's own comment talks
    # about the placeholder syntax, so the leftover check ignores them.
    scan = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    if "{{" in scan or "}}" in scan:
        raise HarnessError(f"{meta.id}: statement.md still contains an unexpanded placeholder")

    headings = {line[3:].strip() for line in scan.splitlines() if line.startswith("## ")}
    missing = [section for section in REQUIRED_SECTIONS if section not in headings]
    if missing:
        raise HarnessError(f"{meta.id}: statement.md is missing the section(s): {', '.join(missing)}")
    return text


# Thai combining marks: the vowel signs and tone marks that sit above or
# below a base consonant. U+0E33 (SARA AM) is a single character that renders
# as nikhahit + sara aa, and extractors hand it back decomposed.
THAI_COMBINING = set("ั") | {chr(code) for code in range(0x0E34, 0x0E3B)} \
    | {chr(code) for code in range(0x0E47, 0x0E4F)}
# The TLWG fonts carry the lowered / shifted variants of those marks as
# PRIVATE-USE glyphs (U+F700-U+F71A), and that is the codepoint pdftotext
# hands back for them — e.g. ข้อ comes out as "ข" + U+F70B + "อ". Seeing
# these is positive evidence the Thai marks were typeset; they just are not
# the canonical characters, so the probe strips them like the canonical ones.
THAI_PUA_MARKS = {chr(code) for code in range(0xF700, 0xF71B)}
THAI_BASE_RANGE = (0x0E01, 0x0E30)


def thai_comparison_key(text: str) -> str:
    """Normalize text for the PDF probe comparison.

    pdftotext reproduces Thai BASE characters faithfully but is lossy about
    the marks stacked on them: it drops some, reorders others past the
    following consonant, and decomposes SARA AM. That is an extractor
    limitation, not a rendering fault — the marks are drawn, and
    `assert_thai_survived` separately proves some of them reach the text
    layer. So the probe compares on whitespace-free, mark-free text: base
    characters, in order, which is what actually proves the Thai was laid out
    with a Thai font rather than dropped or boxed.
    """
    squashed = "".join(text.split()).replace("ำ", "า")
    dropped = THAI_COMBINING | THAI_PUA_MARKS
    return "".join(character for character in squashed if character not in dropped)


def extract_pdf_text(meta: Meta, pdf_path: Path, work_dir: Path) -> str:
    """The text the finished PDF itself carries.

    Eyeballing the PDF would not catch a missing font — wkhtmltopdf will
    happily draw boxes — so every statement check below reads this back out of
    the rendered file rather than trusting the HTML that went in.
    """
    work_dir.mkdir(parents=True, exist_ok=True)
    text_path = work_dir / "statement.txt"
    completed = subprocess.run(
        ["pdftotext", "-enc", "UTF-8", str(pdf_path), str(text_path)],
        capture_output=True, text=True, check=False,
    )
    if completed.returncode != 0 or not text_path.is_file():
        raise HarnessError(f"{meta.id}: pdftotext failed: {(completed.stderr or '').strip()[:400]}")
    return text_path.read_text(encoding="utf-8", errors="replace")


def assert_thai_survived(meta: Meta, extracted: str) -> str:
    """Look for the Thai in the text extracted from the PDF."""
    haystack = thai_comparison_key(extracted)

    base_count = sum(1 for character in extracted
                     if THAI_BASE_RANGE[0] <= ord(character) < THAI_BASE_RANGE[1])
    if base_count < 200:
        raise HarnessError(
            f"{meta.id}: only {base_count} Thai characters came back out of the PDF. "
            "The statement almost certainly rendered without a Thai font."
        )
    marks = sum(1 for character in extracted
                if character in THAI_COMBINING or character in THAI_PUA_MARKS)
    if marks < 50:
        raise HarnessError(
            f"{meta.id}: the PDF carries Thai consonants but only {marks} Thai vowel or "
            "tone marks — the font is missing its mark glyphs."
        )

    for probe in [meta.pdf_probe, *REQUIRED_SECTIONS]:
        if thai_comparison_key(probe) not in haystack:
            raise HarnessError(
                f"{meta.id}: the Thai text \"{probe}\" is NOT in the rendered PDF "
                f"(extracted {base_count} Thai characters). Either the statement rendered "
                "with a font that lacks those glyphs, or that section is missing."
            )
    return meta.pdf_probe


def math_probes(markdown: str) -> list[str]:
    """The `$...$` expressions whose rendering is worth asserting on, longest
    first, de-duplicated."""
    seen: dict[str, str] = {}
    for tex in mdrender.math_spans(markdown):
        try:
            expected = mdrender.math_probe_text(tex)
        except mdrender.MathError as error:
            raise HarnessError(f"statement math ${tex}$: {error}") from error
        if expected is None or len(expected) < MATH_PROBE_MIN_LENGTH:
            continue
        seen.setdefault(expected, tex)
    return sorted(seen, key=len, reverse=True)


def assert_math_survived(meta: Meta, extracted: str, markdown: str) -> str:
    """Prove the server-side math rendering reached the PDF's text layer.

    wkhtmltopdf's WebKit cannot run KaTeX/MathJax, so mdrender lays the math
    out as Unicode symbols, <sub>/<sup> and stacked spans. That means the
    expressions end up as real text in the PDF — and this check extracts them
    back out, exactly like the Thai probe: every `$...$` in the statement must
    be findable in pdftotext's output. A relation glyph the font lacks, or a
    superscript that silently vanished, fails the build here.

    Comparison is on whitespace-free text (a wrapped line must not matter) and
    stacked constructs are excluded, since their reading order is a property
    of the extractor rather than of the rendering.
    """
    probes = math_probes(markdown)
    if not probes:
        raise HarnessError(
            f"{meta.id}: the statement carries no checkable math. Write the bounds and "
            "complexities as LaTeX ($n \\leq 10^5$, $O(1)$) — the template's own style — so "
            "the renderer and the PDF are actually verified."
        )
    haystack = "".join(extracted.split())
    missing = [probe for probe in probes if probe not in haystack]
    if missing:
        raise HarnessError(
            f"{meta.id}: the rendered math {missing[0]!r} is NOT in the text extracted from "
            f"the PDF ({len(missing)} of {len(probes)} expressions missing). The symbol font "
            "is missing a glyph, or the math did not render."
        )
    return probes[0]


def assert_statement_survived(meta: Meta, pdf_path: Path, work_dir: Path,
                              markdown: str) -> tuple[str, str]:
    """Both PDF probes in one pdftotext pass: (Thai probe, math probe)."""
    extracted = extract_pdf_text(meta, pdf_path, work_dir)
    return (assert_thai_survived(meta, extracted),
            assert_math_survived(meta, extracted, markdown))


# --- compile & run ---------------------------------------------------------


@dataclass
class RunResult:
    exit_code: int
    wall_ms: float
    max_rss_kb: int
    timed_out: bool
    stdout_path: Path
    stderr_path: Path

    @property
    def max_rss_mb(self) -> float:
        return self.max_rss_kb / 1024.0


def compile_header_program(workspace: Path, cpp_sources: list[str], binary: str = BINARY_NAME) -> tuple[bool, str]:
    """Compile exactly the way the judge compiles a header submission."""
    command = ["g++", *CPP_COMPILE_FLAGS, *HEADER_EXTRA_FLAGS, *sorted(cpp_sources), "-o", binary]
    completed = subprocess.run(command, cwd=workspace, capture_output=True, text=True, check=False)
    return completed.returncode == 0, (completed.stderr or completed.stdout or "").strip()


def run_program(workspace: Path, binary: str, input_path: Path, time_limit_ms: int,
                stdout_path: Path, stderr_path: Path) -> RunResult:
    """Run one case under the judge's wall-clock rule.

    `timeout -k 2s <limit>s` is the judge's own invocation, so exit code 124
    here means exactly what it means on the judge: Time Limit Exceeded. Peak
    memory comes from os.wait4, which reports the rusage of this child (and
    the descendants it reaped), rather than a process-wide high-water mark.
    """
    limit_s = max(time_limit_ms / 1000.0, 0.001)
    argv = ["timeout", "-k", f"{KILL_GRACE_S}s", f"{limit_s}s", f"./{binary}"]

    stdout_path.parent.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    in_fd = os.open(input_path, os.O_RDONLY)
    out_fd = os.open(stdout_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o644)
    err_fd = os.open(stderr_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o644)
    try:
        pid = os.fork()
        if pid == 0:  # child
            try:
                os.chdir(workspace)
                os.dup2(in_fd, 0)
                os.dup2(out_fd, 1)
                os.dup2(err_fd, 2)
                os.execvp(argv[0], argv)
            except BaseException:
                pass
            os._exit(127)
        _, status, usage = os.wait4(pid, 0)
    finally:
        for fd in (in_fd, out_fd, err_fd):
            os.close(fd)
    wall_ms = (time.monotonic() - started) * 1000.0

    exit_code = os.waitstatus_to_exitcode(status)
    if exit_code < 0:  # died from a signal: the judge reports 128 + signal
        exit_code = 128 - exit_code
    return RunResult(
        exit_code=exit_code,
        wall_ms=wall_ms,
        max_rss_kb=int(usage.ru_maxrss),
        timed_out=exit_code == 124,
        stdout_path=stdout_path,
        stderr_path=stderr_path,
    )


