#!/usr/bin/env python3
"""Shared machinery for build.py and verify.py.

Everything that both scripts must agree on lives here exactly once: where the
files are, what a valid meta.json is, how a header is composed from a topic
template, how C++ is compiled and run, and how output is compared. Drift
between "how the build produced the outputs" and "how the verifier checks
them" would be invisible and would poison all 50 problems, so there is one
implementation of each.

The compile flags, the TLE rule and the output comparison are MIRRORS of the
production judge:

  * flags          backend/constants/index.ts  CPP_COMPILE_FLAGS
                   + HEADER_CPP_PREPARE (-fno-diagnostics-show-caret)
  * TLE            backend/services/judgeService.ts
                   `timeout -k 2s <limit>s ...`, exit code 124
  * comparison     backend/utils/outputComparison.ts  normalizeOutput
  * categories     backend/constants/index.ts  PROBLEM_CATEGORIES
  * id / filename  backend/utils/problemFilename.ts, problemZipConfig.ts

Change one of those in the backend and this file has to follow.
"""

